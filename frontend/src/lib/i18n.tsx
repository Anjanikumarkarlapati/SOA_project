interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  activeMeta: LanguageMeta;
  t: (key: string, fallback?: string) => string;
  isIndic: boolean;
}

export type Language = LanguageCode;

const LANGUAGE_STORAGE_KEY = "agritech_lang";
let memoryFallbackLanguage: LanguageCode = "en";
const languageListeners = new Set<() => void>();

function isValidLanguageCode(value: unknown): value is LanguageCode {
  return typeof value === "string" && SUPPORTED_LANGUAGES.some((l) => l.code === value);
}

function getServerLanguageSnapshot(): LanguageCode {
  return "en";
}

function getClientLanguageSnapshot(): LanguageCode {
  try {
    if (typeof window === "undefined") return "en";
    const storage = window.localStorage;
    if (storage) {
      const saved = storage.getItem(LANGUAGE_STORAGE_KEY);
      const resolved = isValidLanguageCode(saved) ? saved : "en";
      memoryFallbackLanguage = resolved;
      return resolved;
    }
  } catch {
    // localStorage unavailable or threw SecurityError; fall back to in-memory selection
  }
  return memoryFallbackLanguage;
}

function subscribeLanguage(listener: () => void): () => void {
  languageListeners.add(listener);
  const onStorage = (e: StorageEvent) => {
    if (e.key === null || e.key === LANGUAGE_STORAGE_KEY) {
      listener();
    }
  };
  if (typeof window !== "undefined") {
    window.addEventListener("storage", onStorage);
  }
  return () => {
    languageListeners.delete(listener);
    if (typeof window !== "undefined") {
      window.removeEventListener("storage", onStorage);
    }
  };
}

function persistLanguage(newLang: LanguageCode): void {
  if (!isValidLanguageCode(newLang)) return;
  memoryFallbackLanguage = newLang;
  try {
    if (typeof window !== "undefined") {
      window.localStorage?.setItem(LANGUAGE_STORAGE_KEY, newLang);
    }
  } catch {
    // ignore restricted storage; memoryFallbackLanguage retains selection
  }
  languageListeners.forEach((listener) => listener());
}

export function translate(
  language: LanguageCode,
  key: string,
  fallback?: string
): string {
  const extraLang = M2_TRANSLATIONS[language];
  if (extraLang && Object.hasOwn(extraLang, key) && extraLang[key]) {
    return extraLang[key];
  }
  const langDict = TRANSLATIONS[language];
  if (langDict && Object.hasOwn(langDict, key) && langDict[key]) {
    return langDict[key];
  }
  const extraEn = M2_TRANSLATIONS.en;
  if (extraEn && Object.hasOwn(extraEn, key) && extraEn[key]) {
    return extraEn[key];
  }
  const defaultDict = TRANSLATIONS.en;
  if (defaultDict && Object.hasOwn(defaultDict, key) && defaultDict[key]) {
    return defaultDict[key];
  }
  return fallback ?? key;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const language = useSyncExternalStore(
    subscribeLanguage,
    getClientLanguageSnapshot,
    getServerLanguageSnapshot
  );

  const activeMeta = useMemo(() => {
    return SUPPORTED_LANGUAGES.find((l) => l.code === language) || SUPPORTED_LANGUAGES[0];
  }, [language]);

  // Synchronize <html> attributes: lang, data-lang-script, and CSS variable adjustments
  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = activeMeta.code;
      document.documentElement.dataset.langScript = activeMeta.script;
      document.documentElement.style.setProperty("--indic-line-height", activeMeta.lineHeight);
      document.documentElement.style.setProperty("--font-serif", activeMeta.fontSerif);
      document.documentElement.style.setProperty("--font-sans", activeMeta.fontSans);
    }
  }, [activeMeta]);

  const setLanguage = useCallback((newLang: LanguageCode) => {
    persistLanguage(newLang);
  }, []);

  const t = useCallback(
    (key: string, fallback?: string): string => translate(language, key, fallback),
    [language]
  );

  const isIndic = activeMeta.script !== "latin";

  const value = useMemo(
    () => ({ language, setLanguage, activeMeta, t, isIndic }),
    [language, setLanguage, activeMeta, t, isIndic]
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return ctx;
}

export const useI18n = useLanguage;
